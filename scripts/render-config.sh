#!/usr/bin/env bash
# Deterministic configuration renderer; no Docker/network dependency.
set -euo pipefail
if [[ $# -ne 6 ]]; then
  echo "Usage: $0 NODE_ID IP_A IP_B IP_C UPSTREAM_YACY_INIT OUTPUT_DIR" >&2
  exit 2
fi
NODE_ID="$1"; IP_A="$2"; IP_B="$3"; IP_C="$4"; BASE_INIT="$5"; OUT_DIR="$6"

validate_ip() {
  local ip="$1" part
  local -a octets
  [[ "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "Invalid IPv4: $ip" >&2; exit 2; }
  IFS=. read -r -a octets <<< "$ip"
  [[ ${#octets[@]} -eq 4 ]] || exit 2
  for part in "${octets[@]}"; do
    [[ ${#part} -le 3 ]] && (( 10#$part <= 255 )) || { echo "Invalid IPv4: $ip" >&2; exit 2; }
  done
}
for ip in "$IP_A" "$IP_B" "$IP_C"; do validate_ip "$ip"; done
case "$NODE_ID" in
  ubuntu-a) NODE_IP="$IP_A"; PRINCIPAL=yes ;;
  ubuntu-b) NODE_IP="$IP_B"; PRINCIPAL=yes ;;
  macos-c)  NODE_IP="$IP_C"; PRINCIPAL=no ;;
  *) echo "Node must be ubuntu-a, ubuntu-b or macos-c" >&2; exit 2 ;;
esac
[[ -s "$BASE_INIT" ]] || { echo "Upstream yacy.init missing: $BASE_INIT" >&2; exit 2; }
mkdir -p "$OUT_DIR"
INIT="$OUT_DIR/yacy.init"
UNIT="$OUT_DIR/yacy.network.route-A.unit"
cp "$BASE_INIT" "$INIT"

# Replace a key without destroying other upstream defaults. Insert missing keys
# (notably seedURL) once. No user-supplied values are executed.
set_property() {
  local key="$1" value="$2" tmp
  tmp="$(mktemp)"
  awk -v k="$key" -v v="$value" '
    BEGIN { found=0 }
    /^[[:space:]]*#/ { print; next }
    {
      raw=$0
      p=index(raw,"=")
      if (p>0) {
        left=substr(raw,1,p-1)
        gsub(/^[[:space:]]+|[[:space:]]+$/, "", left)
        if (left==k) {
          if (!found) print k "=" v
          found=1
          next
        }
      }
      print
    }
    END { if (!found) print k "=" v }
  ' "$INIT" > "$tmp"
  cat "$tmp" > "$INIT"
  rm -f "$tmp"
}
set_property network.unit.definition "defaults/yacy.network.route-A.unit"
set_property network.unit.agent "$NODE_ID"
set_property peerName "$NODE_ID"
set_property staticIP "$NODE_IP"
set_property yacyDebugMode "true"
set_property upnp.enabled "false"
set_property browserPopUpTrigger "false"
set_property allowDistributeIndex "true"
set_property allowReceiveIndex "true"
set_property crawlResponse "true"
set_property seedFilePath "DATA/HTDOCS/seed.txt"
set_property seedURL "http://$NODE_IP:8090/seed.txt"
if [[ "$PRINCIPAL" == "yes" ]]; then
  set_property seedUploadMethod "File"
else
  set_property seedUploadMethod "none"
fi

# Whitelist peer addresses only, rather than all private subnets.
ipregex() { printf '%s' "$1" | sed 's/\./\\\\./g'; }
ALLOW="$(ipregex "$IP_A"),$(ipregex "$IP_B"),$(ipregex "$IP_C"),127\\.0\\.0\\.1,localhost"
cat > "$UNIT" <<EOF
# Generated by render-config.sh. The SAME unit file must be used on all peers.
network.unit.name = homeweb
network.unit.description = Three-host private YaCy search network
network.unit.domain = global
network.unit.remotesearch.maxtime = 4000
network.unit.remotesearch.maxcount = 20
network.unit.dht = true
network.unit.dhtredundancy.junior = 1
network.unit.dhtredundancy.senior = 2
network.unit.dht.partitionExponent = 0
network.unit.inspection.searchverify = false
network.unit.remotecrawl.speed = 1000
network.unit.bootstrap.seedlist0 = http://${IP_A}:8090/seed.txt
network.unit.bootstrap.seedlist1 = http://${IP_B}:8090/seed.txt
network.unit.protocol.control = uncontrolled
network.unit.access.whitelist = ${ALLOW}
network.unit.access.blacklist =
greedylearning.enabled = false
EOF

# Fail closed when a bad transformation might let a new peer join freeworld.
grep -Eq '^network\.unit\.definition=defaults/yacy\.network\.route-A\.unit$' "$INIT"
grep -Eq '^network\.unit\.name = homeweb$' "$UNIT"
if grep -E '^network\.unit\.bootstrap\.seedlist[0-9]+ ?=' "$UNIT" | grep -Eq 'yacy.net|freeworld'; then
  echo "Refusing public YaCy bootstrap" >&2
  exit 1
fi
printf 'Rendered %s (%s), private network = homeweb\n' "$NODE_ID" "$NODE_IP"
